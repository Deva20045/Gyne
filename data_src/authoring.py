"""Small, strict reader for hand-authored, page-ordered question blocks.

Fields: format | stem | correct | distractor 1 | distractor 2 | distractor 3 | explanation.
No questions or distractors are generated by this helper.
"""
FORMATS = {'fillup', 'match', 'tf', 'scenario', 'odd', 'recall'}


def add(sections, page, title, text):
    questions = []
    for line in text.strip().splitlines():
        if not line.strip():
            continue
        fields = [x.strip() for x in line.split('|')]
        if len(fields) != 7:
            raise ValueError(f'Page {page}: expected seven fields: {line}')
        fmt, stem, answer, a, b, c, why = fields
        if fmt not in FORMATS or not all(fields):
            raise ValueError(f'Page {page}: invalid question: {line}')
        if len({answer.casefold(), a.casefold(), b.casefold(), c.casefold()}) != 4:
            raise ValueError(f'Page {page}: repeated options: {stem}')
        questions.append((stem, answer, [a, b, c], why, fmt, page))
    sections.append((title, [(title, questions)]))
